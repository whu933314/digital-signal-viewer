# -*- coding: utf-8 -*-
"""產生 Windows exe 的版本資訊檔（PyInstaller --version-file），讓檔案總管「內容 → 詳細資料」看得到版本。

    python tools\\make_version_file.py [輸出路徑]        # 預設 build_version_info.txt（在專案根目錄；.gitignore 已排除）

版本號取自 signal_viewer.py 的 APP_VERSION（直接讀原始碼，不 import——不用載入 tkinter／matplotlib）：
FileVersion／ProductVersion 字串＝APP_VERSION（例如 "3.4"），固定欄位 filevers／prodvers＝補滿 4 段的數字（3, 4, 0, 0），
ProductName＝Digital Signal Viewer。CompanyName 留空、不放任何個人資訊。
格式是 PyInstaller 的 VSVersionInfo 文字（PyInstaller.utils.win32.versioninfo.load_version_info_from_text_file 讀得進去）。
"""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRODUCT_NAME = "Digital Signal Viewer"
FILE_DESCRIPTION = "Digital Signal Viewer - waveform viewer for digital/IQ signals"
EXE_NAME = "SignalViewer.exe"
DEFAULT_OUT = os.path.join(ROOT, "build_version_info.txt")


def app_version(path: str = os.path.join(ROOT, "signal_viewer.py")) -> str:
    """signal_viewer.py 裡的 APP_VERSION = "x.y"。"""
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r'^APP_VERSION\s*=\s*["\']([^"\']+)["\']', line)
            if m:
                return m.group(1).strip()
    raise ValueError(f"APP_VERSION not found in {path}")


def version_tuple(ver: str) -> tuple:
    """"3.4" → (3, 4, 0, 0)；非數字的部分（例如 3.4b1 的 b1）只取前面的數字；每段 0..65535。"""
    nums = []
    for part in str(ver).split(".")[:4]:
        m = re.match(r"\d+", part.strip())
        nums.append(min(65535, int(m.group(0))) if m else 0)
    while len(nums) < 4:
        nums.append(0)
    return tuple(nums)


def _q(s: str) -> str:
    return repr(str(s))


def version_file_text(ver: str) -> str:
    """PyInstaller 版本資訊檔的內容（VSVersionInfo；語言 0x0409 英文（美國）、字碼頁 1200 Unicode）。"""
    vt = version_tuple(ver)
    strings = [("CompanyName", ""), ("FileDescription", FILE_DESCRIPTION), ("FileVersion", ver),
               ("InternalName", "SignalViewer"), ("LegalCopyright", ""), ("OriginalFilename", EXE_NAME),
               ("ProductName", PRODUCT_NAME), ("ProductVersion", ver)]
    rows = ",\n".join(f"          StringStruct({_q(k)}, {_q(v)})" for k, v in strings)
    return f"""# UTF-8
# Generated by tools/make_version_file.py from signal_viewer.APP_VERSION = {ver!r}
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
{rows}
          ])
      ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_version_file(out: str = DEFAULT_OUT, ver: str = "") -> str:
    ver = ver or app_version()
    with open(out, "w", encoding="utf-8") as f:
        f.write(version_file_text(ver))
    return out


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    out = argv[0] if argv else DEFAULT_OUT
    ver = app_version()
    write_version_file(out, ver)
    print(f"[make_version_file] {out}: {PRODUCT_NAME} {ver} {version_tuple(ver)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
